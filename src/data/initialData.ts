// Helper to generate 3 months of attendance history
export function generateInitialAttendance(): AttendanceRecord[] {
  const records: AttendanceRecord[] = [];
  const students = INITIAL_STUDENTS;
  
  // Working days in last 3 months
  // For Rahul Sharma (std-001): exactly 23 present, 2 absent, 0 late in current demo month (Nov 2026)
  const daysInNov = [
    '2026-11-01', '2026-11-02', '2026-11-03', '2026-11-04', '2026-11-05',
    '2026-11-06', '2026-11-07', '2026-11-08', '2026-11-09'
  ];

  // Populate last 25 past working days up to 2026-11-08 for demo month stats
  const pastDates: string[] = [];
  for (let i = 25; i >= 1; i--) {
    const d = new Date(2026, 10, 9 - i); // Nov 2026
    if (d.getDay() !== 0) { // skip sundays
      pastDates.push(d.toISOString().split('T')[0]);
    }
  }

  // Pre-seed for Rahul Sharma
  // Rahul: 2 absent days (say 2nd and 14th day of past dates)
  pastDates.forEach((dateStr, idx) => {
    students.forEach((student) => {
      let status: 'present' | 'absent' | 'late' = 'present';
      if (student.id === 'std-001') {
        if (idx === 3 || idx === 11) {
          status = 'absent';
        } else {
          status = 'present';
        }
      } else {
        // deterministic distribution
        const hash = (parseInt(student.rollNo) + idx * 7) % 20;
        if (hash === 0) status = 'absent';
        else if (hash === 1) status = 'late';
        else status = 'present';
      }

      records.push({
        id: `att-${student.id}-${dateStr}`,
        studentId: student.id,
        date: dateStr,
        status,
        markedByTeacherId: 't-001',
        markedByName: 'Dr. Rajesh Mehta',
        timestamp: `${dateStr}T09:30:00Z`,
        remarks: status === 'absent' ? 'Parent informed via WhatsApp' : undefined,
      });
    });
  });

  return records;
}

